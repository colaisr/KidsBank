import "@fontsource-variable/inter";
import "./leo-configurator.css";
import { createRoot } from "react-dom/client";
import { createElement } from "react";
import { useEffect, useRef, useState, type Ref } from "react";
import { Pause, Play } from "lucide-react";
import { Button } from "@/components/ui/button";
import { ColorPickerPopover } from "@/components/ui/color-picker";
import { Select, SelectContent, SelectItem, SelectTrigger } from "@/components/ui/select";
import { Slider } from "@/components/ui/slider";

type MascotElement = HTMLElement & {
  color: string;
  emotion: string;
  ready: Promise<void>;
  poster?: HTMLImageElement;
  snapshot: () => Promise<Blob>;
};
declare global {
  interface Window { EVOCA_LEO_CONFIG?: { primaryColor?: string; maneColor?: string; poster?: string }; LionColor?: { validHex: (s: string) => boolean; toHSL: (s: string) => number[]; fromHSL: (...v: number[]) => string } }
}
const banks = [
  { name: "Evoca", color: "#6A00DE" },
  { name: "AMIO", color: "#05A8B5" },
  { name: "Converse", color: "#1767A8" },
  { name: "ACBA", color: "#28A85A" },
];
const emotions = [
  ["wink", "Подмигивает"], ["laugh", "Смеётся"], ["surprise", "Удивляется"],
  ["think", "Думает"], ["feed", "Ест апельсин"], ["play", "Играет с мячом"], ["rest", "Отдыхает"],
];
const backgrounds = [["light", "Светлый"], ["dark", "Тёмный"], ["purple", "Фирменный"]];
const initialColor = () => {
  const configured = window.EVOCA_LEO_CONFIG?.primaryColor || window.EVOCA_LEO_CONFIG?.maneColor;
  return window.LionColor?.validHex(configured || "") ? configured!.toUpperCase() : "#6A00DE";
};
function download(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a"); a.href = url; a.download = filename; a.click();
  window.setTimeout(() => URL.revokeObjectURL(url), 30000);
}
function asDataUrl(blob: Blob) {
  return new Promise<string>((resolve, reject) => {
    const reader = new FileReader(); reader.onload = () => resolve(String(reader.result)); reader.onerror = reject; reader.readAsDataURL(blob);
  });
}
function App() {
  const mascotRef = useRef<MascotElement>(null);
  const [color, setColor] = useState(initialColor);
  const [emotion, setEmotion] = useState("wink");
  const [background, setBackground] = useState("light");
  const [paused, setPaused] = useState(matchMedia("(prefers-reduced-motion: reduce)").matches);
  const [status, setStatus] = useState("");
  const [busy, setBusy] = useState(false);
  const [hue, setHue] = useState(() => (window.LionColor?.toHSL(initialColor())[0] ?? 0) * 360);

  useEffect(() => {
    const leo = mascotRef.current;
    if (leo) leo.color = color;
    document.documentElement.style.setProperty("--brand", color);
    document.documentElement.style.setProperty("--fluid-primary", color);
    document.documentElement.style.setProperty("--color-primary", color);
    document.documentElement.dataset.previewBackground = background;
  }, [color, background]);
  useEffect(() => {
    const leo = mascotRef.current;
    if (leo) {
      leo.emotion = emotion;
      if (paused) leo.setAttribute("paused", ""); else leo.removeAttribute("paused");
    }
  }, [emotion, paused]);

  const changeHue = (value: number | [number, number]) => {
    const nextHue = typeof value === "number" ? value : value[0];
    setHue(nextHue);
    const hsl = window.LionColor?.toHSL(color);
    if (hsl && window.LionColor) {
      if (hsl[1] < 0.03) { hsl[1] = 1; hsl[2] = 0.43; }
      hsl[0] = nextHue / 360;
      setColor(window.LionColor.fromHSL(...hsl).toUpperCase());
    }
  };
  const chooseColor = (value: string) => {
    if (!window.LionColor?.validHex(value)) return;
    const hex = value.toUpperCase(); setColor(hex);
    setHue((window.LionColor.toHSL(hex)[0] ?? 0) * 360);
  };
  const exportPng = async () => {
    const leo = mascotRef.current; if (!leo) return;
    try { await leo.ready; download(await leo.snapshot(), `leo-${emotion}-${color.slice(1)}.png`); setStatus("PNG сохранён"); }
    catch { setStatus("Не удалось сохранить PNG. Попробуйте ещё раз."); }
  };
  const exportSettings = async () => {
    const leo = mascotRef.current; if (!leo) return;
    setBusy(true); setStatus("");
    const poster = document.createElement("lion-mascot") as MascotElement;
    poster.color = color; poster.emotion = "wink"; poster.setAttribute("paused", "");
    poster.style.cssText = "position:fixed;left:-2000px;top:0;pointer-events:none"; document.body.append(poster);
    try {
      await poster.ready;
      if (!poster.poster?.naturalWidth) throw new Error("Mascot poster did not load");
      const posterData = await asDataUrl(await poster.snapshot());
      const settings = { primaryColor: color, maneColor: color, poster: posterData };
      download(new Blob(["// Generated by the Evoca Kids Leo configurator.\nwindow.EVOCA_LEO_CONFIG = ", JSON.stringify(settings, null, 2), ";\n"], { type: "text/javascript" }), "leo-config.js");
      setStatus("Настройки приложения сохранены");
    } catch { setStatus("Не удалось подготовить настройки. Проверьте загрузку Лео."); }
    finally { poster.remove(); setBusy(false); }
  };

  return <main className="config-page">
    <header className="config-header"><h1>Настроить Лео</h1></header>
    <section className="config-layout" aria-label="Настройки персонажа">
      <div className="preview-frame" data-background={background}>
        {createElement("lion-mascot", { ref: mascotRef as unknown as Ref<HTMLElement>, className: "mascot", color, emotion, autoplay: "" })}
        <div className="video-controls">
          <div className="video-selects">
            <label className="control-field"><span>Эмоция</span>
              <Select value={emotion} onValueChange={setEmotion} size="default">
                <SelectTrigger className="video-select-trigger" aria-label="Эмоция" />
                <SelectContent className="config-select-popup">{emotions.map(([key, label], index) => <SelectItem key={key} index={index} value={key}>{label}</SelectItem>)}</SelectContent>
              </Select>
            </label>
            <label className="control-field"><span>Фон</span>
              <Select value={background} onValueChange={setBackground} size="default">
                <SelectTrigger className="video-select-trigger" aria-label="Фон" />
                <SelectContent className="config-select-popup">{backgrounds.map(([key, label], index) => <SelectItem key={key} index={index} value={key}>{label}</SelectItem>)}</SelectContent>
              </Select>
            </label>
          </div>
          <button className="playback-toggle" type="button" onClick={() => setPaused(v => !v)} aria-label={paused ? "Продолжить анимацию" : "Пауза"} aria-pressed={paused}>
            {paused ? <Play size={19} fill="currentColor" /> : <Pause size={19} fill="currentColor" />}
          </button>
        </div>
      </div>
      <section className="theme-panel" aria-label="Основной цвет приложения">
        <div className="theme-heading"><h2>Основной цвет</h2>
          <ColorPickerPopover value={color} onValueChange={chooseColor} format="hex" triggerShowValue triggerClassName="brand-picker-trigger" className="fluid-color-picker" aria-label="Выбрать основной цвет" />
        </div>
        <div className="hue-control" aria-label="Спектр цветов">
          <Slider value={hue} onChange={changeHue} min={0} max={360} step={1} showValue={false} hideFill thumbColor={`hsl(${hue}, 100%, 50%)`} thumbBorderColor="#ffffff" trackStyle={{ background: "linear-gradient(90deg,#ef4444,#f59e0b,#84cc16,#14b86e,#06b6d4,#3b82f6,#8b5cf6,#d946ef,#ef4444)", borderColor: "transparent" }} aria-label="Оттенок" />
        </div>
        <div className="presets-section"><div className="section-label">Цветовые пресеты</div><div className="bank-presets" role="group" aria-label="Примеры цветов банков">
          {banks.map(bank => <button className={`bank-preset${color === bank.color ? " selected" : ""}`} key={bank.name} type="button" onClick={() => chooseColor(bank.color)} aria-pressed={color === bank.color}>
            <span className="bank-dot" style={{ backgroundColor: bank.color }} />{bank.name}
          </button>)}
        </div></div>
        <div className="export-actions">
          <Button variant="primary" className="export-primary" loading={busy} onClick={exportSettings}>Скачать настройки приложения</Button>
          <Button variant="secondary" className="export-secondary" onClick={exportPng}>Скачать PNG</Button>
        </div>
        <div className="save-status" role="status" aria-live="polite">{status}</div>
      </section>
    </section>
  </main>;
}

createRoot(document.getElementById("root")!).render(<App />);
